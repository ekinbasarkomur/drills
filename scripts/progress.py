#!/usr/bin/env python3
"""Work out what is solved in which language, by running the tests.

    scripts/progress.py                 print the grid
    scripts/progress.py two_sum ...     only those exercises
    scripts/progress.py --write         rewrite the PROGRESS.md files and the
                                        totals in README.md

Status comes from running each exercise's tests, never from reading the file,
so the tables cannot drift from reality.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALGO = ROOT / "algorithms"

# NeetCode 150 presents the problems in these sections, in this order.
SECTIONS = [
    ("Arrays & Hashing", ["contains_duplicate", "valid_anagram", "two_sum",
                          "group_anagrams", "top_k_frequent", "encode_decode_strings",
                          "products_of_array_except_self", "valid_sudoku",
                          "longest_consecutive_sequence"]),
    ("Two Pointers", ["valid_palindrome", "two_sum_ii", "three_sum",
                      "container_with_most_water", "trapping_rain_water"]),
    ("Sliding Window", ["best_time_to_buy_and_sell_stock",
                        "longest_substring_without_repeating",
                        "longest_repeating_character_replacement"]),
    ("Stack", ["valid_parentheses", "min_stack", "daily_temperatures"]),
    ("Binary Search", ["binary_search", "koko_eating_bananas",
                       "search_in_rotated_sorted_array"]),
    ("Linked List", ["reverse_linked_list", "merge_two_sorted_lists",
                     "linked_list_cycle", "lru_cache"]),
    ("Trees", ["invert_binary_tree", "maximum_depth_of_binary_tree"]),
    ("Heap / Priority Queue", ["kth_largest_element_in_a_stream", "last_stone_weight"]),
    ("Graphs", ["number_of_islands"]),
    ("Greedy", ["maximum_subarray"]),
    ("Intervals", ["merge_intervals"]),
]

LANGS = ["rust", "python", "cpp"]


def header(name):
    """Problem number, title and URL, read from the C++ file's header comment."""
    text = (ALGO / "cpp" / "solutions" / f"{name}.cpp").read_text()[:600]
    num = re.search(r"^// (\d+)\.\s*(.+?)\s*(?:https://\S+)?$", text, re.M)
    url = re.search(r"(https://leetcode\.com/problems/[a-z0-9\-]+/)", text)
    return int(num.group(1)), num.group(2).strip(), url.group(1)


def solved(name, lang):
    if lang == "rust":
        if not (ALGO / "rust" / "src" / "bin" / f"{name}.rs").exists():
            return False
        out = subprocess.run(["cargo", "test", "--quiet", "--bin", name],
                             cwd=ALGO / "rust", capture_output=True, text=True)
        return "test result: ok" in out.stdout
    if lang == "python":
        if not (ALGO / "python" / "solutions" / f"{name}.py").exists():
            return False
        out = subprocess.run(["uv", "run", "pytest", "-q", f"solutions/{name}.py"],
                             cwd=ALGO / "python", capture_output=True, text=True)
        return out.returncode == 0
    if not (ALGO / "cpp" / "solutions" / f"{name}.cpp").exists():
        return False
    out = subprocess.run(["make", "--no-print-directory", name],
                         cwd=ALGO / "cpp", capture_output=True, text=True)
    return "test result: ok" in out.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("names", nargs="*")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    wanted = set(args.names) if args.names else None
    results = {}
    for _, names in SECTIONS:
        for name in names:
            if wanted and name not in wanted:
                continue
            results[name] = {lang: solved(name, lang) for lang in LANGS}
            print(f"  {name:<42}"
                  + "".join(" ok " if results[name][l] else " -- " for l in LANGS),
                  file=sys.stderr)

    if wanted and wanted - set(results):
        sys.exit(f"no such exercise: {', '.join(sorted(wanted - set(results)))}")

    totals = {l: sum(r[l] for r in results.values()) for l in LANGS}
    total = len(results)
    print(f"\n  rust {totals['rust']}/{total}   python {totals['python']}/{total}"
          f"   cpp {totals['cpp']}/{total}", file=sys.stderr)

    if not args.write:
        return
    if wanted:
        sys.exit("--write needs the full run; drop the exercise names")

    tick = lambda b: "✅" if b else "▢"
    out = [
        "# Algorithms — progress",
        "",
        "Generated by `make progress`; every tick comes from running that",
        "exercise's tests, not from reading the file.",
        "",
        "✅ solved &nbsp;&nbsp; ▢ scaffolded — the file, its header and all its",
        "tests are in place, only the function body is missing.",
        "",
        f"**Rust {totals['rust']}/{total} &nbsp;&nbsp; Python {totals['python']}/{total}"
        f" &nbsp;&nbsp; C++ {totals['cpp']}/{total}**",
        "",
        "Source: [NeetCode 150](https://neetcode.io/practice), numbers and links",
        "are LeetCode's. Pass the **File** name to `make`:",
        "`make two_sum`, `make cpp-two_sum`.",
    ]
    for section, names in SECTIONS:
        done = {l: sum(results[n][l] for n in names) for l in LANGS}
        out += [
            "",
            f"## {section}",
            f"<sub>rust {done['rust']}/{len(names)} &middot; "
            f"python {done['python']}/{len(names)} &middot; "
            f"cpp {done['cpp']}/{len(names)}</sub>",
            "",
            "| # | Problem | Rust | Python | C++ | File |",
            "| --- | --- | :---: | :---: | :---: | --- |",
        ]
        for name in names:
            num, title, url = header(name)
            r = results[name]
            out.append(f"| [{num}]({url}) | {title} | {tick(r['rust'])} | "
                       f"{tick(r['python'])} | {tick(r['cpp'])} | `{name}` |")

    (ALGO / "PROGRESS.md").write_text("\n".join(out) + "\n")
    print(f"\nwrote {ALGO / 'PROGRESS.md'}", file=sys.stderr)

    # Keep the one-line summary in the root README in step.
    readme = ROOT / "README.md"
    text = readme.read_text()
    text = re.sub(
        r"\| \[`algorithms/`\]\(algorithms/\) \|.*\|\n",
        f"| [`algorithms/`](algorithms/) | [NeetCode 150](https://neetcode.io/practice)"
        f" / [LeetCode](https://leetcode.com/) | Rust, Python, C++ |"
        f" rust {totals['rust']}/{total}, python {totals['python']}/{total},"
        f" cpp {totals['cpp']}/{total} | [PROGRESS.md](algorithms/PROGRESS.md) |\n",
        text, count=1)
    readme.write_text(text)
    print(f"updated {readme}", file=sys.stderr)


if __name__ == "__main__":
    main()
